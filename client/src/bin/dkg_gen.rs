use ark_bn254::{Fr, G1Projective};
use ark_ff::{PrimeField, UniformRand};
use ark_serialize::CanonicalSerialize;
use rand::rngs::OsRng;
use serde::Serialize;
use std::fs::File;
use std::io::Write;
use compliant_privacy_stablecoin_client::audit::{DkgPolynomial, PrivateKeyShare, AuditPublicKey, EncryptedAuditKey};

#[derive(Serialize)]
struct NodeDkgData {
    node_id: usize,
    address: String,
    communication_key: String,
    // 3 commitments of the polynomial, represented as hex strings (compressed G1 points)
    commitments: Vec<String>,
    // 5 shares distributed to recipients, represented as hex strings (each is Fr serialized to hex)
    shares: Vec<String>,
    // The final aggregated private key share of this node (Fr serialized to hex)
    aggregated_private_share: String,
}

#[derive(Serialize)]
struct DkgTestData {
    nodes: Vec<NodeDkgData>,
    global_public_key: String,
    // Sample encrypted audit data for testing decryption
    sample_sym_key: String,
    sample_ciphertext: String,
}

fn main() {
    let mut rng = OsRng;

    // Standard Anvil test addresses for the 5 auditors (corrected key 5)
    let addresses = vec![
        "0x70997970C51812dc3A010C7d01b50e0d17dc79C8".to_string(), // Key 1
        "0x3C44CdDdB6a900fa2b585dd299e03d12FA4293BC".to_string(), // Key 2
        "0x90F79bf6EB2c4f870365E785982E1f101E93b906".to_string(), // Key 3
        "0x15d34AAf54267DB7D7c367839AAf71A00a2C6A65".to_string(), // Key 4
        "0x9965507D1a55bcC2695C58ba16FB37d819B0A4dc".to_string(), // Key 5
    ];

    // 1. Generate local polynomials for 5 nodes (threshold t=3)
    let mut polynomials = Vec::new();
    for id in 1..=5 {
        polynomials.push(DkgPolynomial::new(id, 3));
    }

    // 2. Generate local DKG shares matrix: shares[sender][receiver]
    // shares[i][j] is the evaluation of polynomial i at point j (x = j as Fr)
    let mut shares_matrix = vec![vec![Fr::from(0); 6]; 6];
    for i in 1..=5 {
        for j in 1..=5 {
            let x = Fr::from(j as u64);
            shares_matrix[i][j] = polynomials[i - 1].evaluate(x);
        }
    }

    // 3. Aggregate shares received by each node to compute sk_j
    let mut private_shares = Vec::new();
    for j in 1..=5 {
        let mut j_shares = Vec::new();
        for i in 1..=5 {
            j_shares.push(shares_matrix[i][j]);
        }
        private_shares.push(PrivateKeyShare::aggregate(&j_shares, j));
    }

    // 4. Compute DKG commitments (G1 points) for each node
    let mut all_node_commitments = Vec::new();
    for i in 0..5 {
        let comms = polynomials[i].commitments();
        let comm_hexes: Vec<String> = comms
            .iter()
            .map(|p| {
                let mut bytes = Vec::new();
                p.serialize_compressed(&mut bytes).unwrap();
                hex::encode(bytes)
            })
            .collect();
        all_node_commitments.push(comm_hexes);
    }

    // 5. Aggregate global public key (Sum of polynomials[i].commitments[0])
    let mut a0_commitments = Vec::new();
    for poly in &polynomials {
        a0_commitments.push(poly.commitments()[0]);
    }
    let global_pub_key = AuditPublicKey::aggregate(&a0_commitments);
    let mut global_pub_key_bytes = Vec::new();
    global_pub_key.point.serialize_compressed(&mut global_pub_key_bytes).unwrap();
    let global_pub_key_hex = hex::encode(global_pub_key_bytes);

    // 6. Encrypt a sample symmetric key for testing
    let sample_sym_key = Fr::from(5432109876u64);
    let mut sym_key_bytes = Vec::new();
    sample_sym_key.serialize_compressed(&mut sym_key_bytes).unwrap();
    let sample_sym_key_hex = hex::encode(sym_key_bytes);

    let sample_ciphertext = EncryptedAuditKey::encrypt(&global_pub_key, sample_sym_key);
    let sample_ciphertext_hex = hex::encode(sample_ciphertext.to_bytes());

    // 7. Format all node DKG data
    let mut nodes_data = Vec::new();
    for idx in 0..5 {
        let node_id = idx + 1;
        
        // Serialize shares generated by this node to hex
        let mut node_shares = Vec::new();
        for receiver_id in 1..=5 {
            let share_val = shares_matrix[node_id][receiver_id];
            let mut share_bytes = Vec::new();
            share_val.serialize_compressed(&mut share_bytes).unwrap();
            node_shares.push(hex::encode(share_bytes));
        }

        let mut private_share_bytes = Vec::new();
        private_shares[idx].share.serialize_compressed(&mut private_share_bytes).unwrap();

        // Dummy communication keys for testing
        let dummy_comm_key = hex::encode(vec![idx as u8; 32]);

        nodes_data.push(NodeDkgData {
            node_id,
            address: addresses[idx].clone(),
            communication_key: dummy_comm_key,
            commitments: all_node_commitments[idx].clone(),
            shares: node_shares,
            aggregated_private_share: hex::encode(private_share_bytes),
        });
    }

    let test_data = DkgTestData {
        nodes: nodes_data,
        global_public_key: global_pub_key_hex,
        sample_sym_key: sample_sym_key_hex,
        sample_ciphertext: sample_ciphertext_hex,
    };

    // 8. Write to contracts/test/dkg_test_data.json
    let json_str = serde_json::to_string_pretty(&test_data).unwrap();
    let dest_path = "contracts/test/dkg_test_data.json";
    let mut file = File::create(dest_path).unwrap();
    file.write_all(json_str.as_bytes()).unwrap();

    println!("DKG test data successfully written to {}", dest_path);
}
